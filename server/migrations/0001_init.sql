-- Initial schema for cloudflare-ddns.

-- A machine running the DDNS client. One client owns at most one A record.
CREATE TABLE clients (
  id              TEXT PRIMARY KEY,               -- generated by the client on first run
  secret_hash     TEXT NOT NULL,                  -- SHA-256 of the client secret
  status          TEXT NOT NULL DEFAULT 'pending' -- pending | approved | rejected | revoked
                  CHECK (status IN ('pending', 'approved', 'rejected', 'revoked')),
  hostname        TEXT,
  os              TEXT,
  arch            TEXT,
  version         TEXT,
  registered_ip   TEXT NOT NULL,                  -- public IP seen at registration
  current_ip      TEXT,                           -- last IP written to DNS
  zone_id         TEXT,
  zone_name       TEXT,
  record_name     TEXT,                           -- FQDN, e.g. home.example.com
  record_id       TEXT,                           -- Cloudflare DNS record id
  last_error      TEXT,
  first_seen      INTEGER NOT NULL,               -- unix seconds
  last_seen       INTEGER,
  last_ip_change  INTEGER,
  approved_at     INTEGER
);

CREATE INDEX idx_clients_status ON clients (status);
CREATE UNIQUE INDEX idx_clients_record ON clients (record_name) WHERE record_name IS NOT NULL;

-- IPs blocked from registering (e.g. a pending client not approved in time).
CREATE TABLE blocked_ips (
  ip          TEXT PRIMARY KEY,
  reason      TEXT NOT NULL,
  blocked_at  INTEGER NOT NULL
);

-- Key/value app settings, editable from the dashboard.
CREATE TABLE settings (
  key    TEXT PRIMARY KEY,
  value  TEXT NOT NULL
);

INSERT INTO settings (key, value) VALUES
  ('registration_open', 'false'),
  ('approval_timeout_seconds', '300'),
  ('heartbeat_interval_seconds', '60'),
  ('target_client_version', '');

-- Audit log and IP history.
CREATE TABLE events (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  client_id  TEXT,
  type       TEXT NOT NULL,   -- registered | approved | rejected | blocked | unblocked | ip_changed | upgraded | ...
  detail     TEXT,            -- JSON
  created_at INTEGER NOT NULL
);

CREATE INDEX idx_events_client ON events (client_id, created_at);
